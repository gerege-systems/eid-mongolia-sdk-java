package mn.eidmongolia.eid.pades.validate;

import static mn.eidmongolia.eid.pades.validate.PdfObjects.arr;
import static mn.eidmongolia.eid.pades.validate.PdfObjects.dget;
import static mn.eidmongolia.eid.pades.validate.PdfObjects.dict;
import static mn.eidmongolia.eid.pades.validate.PdfObjects.isArr;
import static mn.eidmongolia.eid.pades.validate.PdfObjects.isDict;
import static mn.eidmongolia.eid.pades.validate.PdfObjects.isInt;
import static mn.eidmongolia.eid.pades.validate.PdfObjects.pdfEqual;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import mn.eidmongolia.eid.pades.validate.PdfObjects.PReal;
import mn.eidmongolia.eid.pades.validate.PdfObjects.PRef;
import mn.eidmongolia.eid.pades.validate.PdfObjects.PStr;
import mn.eidmongolia.eid.pades.validate.PdfObjects.PStream;

/**
 * The own-signer shape of a visible signature (APPEARANCE_SPEC.md §5 Validator), a port of TS
 * src/pades/validate/appearance.ts: the widget, its /AP /N form XObject and the form's two fonts (11 objects) are
 * regenerated by the PAdES writer's stamp generator from the signature's own data and compared object by object.
 */
final class OwnAppearance {
    private OwnAppearance() {}

    static final String AP_VERIFY_PREFIX = "https://ca.eidmongolia.mn/verify/";
    /** The /EIDVerify BDC line's first 10 bytes: on an e-Seal signature's form stream it selects the QR seal stamp. */
    private static final byte[] AP_MARKER = PdfObjects.latin1("/EIDVerify");
    private static final Pattern AP_URL_RE = Pattern.compile(
        "/EIDVerify <</URL \\(https://ca\\.eidmongolia\\.mn/verify/([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})"
            + "/([1-9][0-9]?)\\)>> BDC\n");

    private static PdfObjError fail() {
        return PdfObjError.notSignatureOnly();
    }

    /** Go/TS round100: floor(v*100+0.5). */
    static double round100(double v) {
        return Math.floor(v * 100 + 0.5);
    }

    private static boolean startsWith(byte[] b, byte[] p) {
        if (b.length < p.length) return false;
        for (int i = 0; i < p.length; i++) if (b[i] != p[i]) return false;
        return true;
    }

    /** An own-profile visible widget d (object widget): the widget and the 11 /AP objects are exactly the writer's. */
    static void ownVisible(Classifier c, Map<String, Object> d, int widget) {
        if (!Classifier.onlyKeys(d, "Type", "Subtype", "Rect", "P", "F", "FT", "T", "V", "AP")) throw fail();
        Object pr = dget(d, "P");
        Object sr = dget(d, "V");
        Object ap = dget(d, "AP");
        Object t = dget(d, "T");
        if (!(pr instanceof PRef) || !(sr instanceof PRef) || !isDict(ap) || !(t instanceof PStr)
            || !Classifier.onlyKeys(dict(ap), "N") || !c.pages.contains(((PRef) pr).num)) {
            throw fail();
        }
        PRef page = (PRef) pr;
        PRef sig = (PRef) sr;
        Object nro = dget(dict(ap), "N");
        if (!(nro instanceof PRef)) throw fail();
        PRef nr = (PRef) nro;
        double[] box = new double[4];
        int rot = pageGeometry(c, page.num, box);
        Object ra = dget(d, "Rect");
        if (!isArr(ra) || arr(ra).size() != 4) throw fail();
        double[] rect = new double[4];
        for (int i = 0; i < 4; i++) {
            Double v = pdfNumber(arr(ra).get(i));
            if (v == null) throw fail();
            rect[i] = round100(v);
        }
        if (rect[0] >= rect[2] || rect[1] >= rect[3] || rect[0] < box[0] || rect[1] < box[1] || rect[2] > box[2]
            || rect[3] > box[3]) {
            throw fail();
        }
        double w = rect[2] - rect[0];
        double h = rect[3] - rect[1];
        if (rot == 90 || rot == 270) {
            double x = w;
            w = h;
            h = x;
        }
        long[] lrect = {(long) rect[0], (long) rect[1], (long) rect[2], (long) rect[3]};
        sameObject(c, widget, c.support.visibleWidget(((PStr) t).v, lrect, page.num, page.gen, sig.num, nr.num));
        Object sd = c.fin.deref(sig);
        SigMeta meta = c.sigs.get(sig.num);
        if (!isDict(sd) || meta == null || !meta.roleOK) throw fail();
        Object ns = dget(dict(sd), "Name");
        Object ms = dget(dict(sd), "M");
        // A hostile multi-megabyte /Name is kept out of the (quadratic) stamp text wrap.
        if (!(ns instanceof PStr) || !(ms instanceof PStr) || ((PStr) ns).v.length() > Revisions.OWN_TEXT_LIMIT) throw fail();
        String m = ((PStr) ms).v;
        if (!Revisions.ownDate(m) || !m.substring(16).equals("+08'00'")) throw fail();
        String date = m.substring(2, 6) + "-" + m.substring(6, 8) + "-" + m.substring(8, 10) + " " + m.substring(10, 12) + ":"
            + m.substring(12, 14) + " (+08)";
        int[] ids = apIDs(c, nr);
        Object form = c.fin.get(ids[0]);
        if (!(form instanceof PStream)) throw fail();
        byte[] fdata = ((PStream) form).data;
        // The certificate picks the variant (APPEARANCE_SPEC.md §6.1/§6.3); for a seal the stored stream data decides
        // (QR seal stamp when it begins with /EIDVerify). A failure is never retried as the other variant.
        boolean seal = meta.seal;
        String role = "";
        String url = "";
        if (!seal || startsWith(fdata, AP_MARKER)) {
            String head = PdfObjects.latin1(fdata, 0, Math.min(fdata.length, 200));
            Matcher sm = AP_URL_RE.matcher(head);
            if (!sm.lookingAt() || !sm.group(2).equals(String.valueOf(meta.revIndex))
                || (!c.docID.isEmpty() && !sm.group(1).equals(c.docID))) {
                throw fail();
            }
            if (!seal) role = meta.role;
            url = AP_VERIFY_PREFIX + sm.group(1) + "/" + sm.group(2);
        }
        String name = Revisions.pdfTextString((PStr) ns);
        // TS passes w/h as JS numbers; values outside int range cannot be the writer's stamp.
        if (w > Integer.MAX_VALUE || h > Integer.MAX_VALUE) throw fail();
        for (String lang : new String[] {"mn", "en"}) {
            List<byte[]> bodies;
            try {
                bodies = c.support.appearanceObjects((int) w, (int) h, rot, name, role, lang, date, url, seal, ids.clone());
            } catch (RuntimeException e) {
                throw fail();
            }
            boolean match = true;
            for (int i = 0; i < bodies.size(); i++) {
                try {
                    sameObject(c, ids[i], bodies.get(i));
                } catch (PdfObjError e) {
                    match = false;
                    break;
                }
            }
            if (match) return;
        }
        throw fail();
    }

    private static Map<String, Object> apDict(Classifier c, PRef r) {
        Object o = c.fin.deref(r);
        if (isDict(o)) return dict(o);
        if (o instanceof PStream) return ((PStream) o).dict;
        throw fail();
    }

    /** The 11 object numbers from /AP /N (appearanceObjects order); all new, generation 0, distinct. */
    private static int[] apIDs(Classifier c, PRef n) {
        List<PRef> refs = new ArrayList<>();
        refs.add(n);
        Map<String, Object> form = apDict(c, n);
        Object res = dget(form, "Resources");
        Object fonts = dget(isDict(res) ? dict(res) : null, "Font");
        for (String key : new String[] {"F1", "F2"}) {
            Object t0 = dget(isDict(fonts) ? dict(fonts) : null, key);
            if (!(t0 instanceof PRef)) throw fail();
            Map<String, Object> td = apDict(c, (PRef) t0);
            Object desc = dget(td, "DescendantFonts");
            Object tu = dget(td, "ToUnicode");
            if ((isArr(desc) ? arr(desc).size() : 0) != 1 || !(tu instanceof PRef)) throw fail();
            Object cid = arr(desc).get(0);
            if (!(cid instanceof PRef)) throw fail();
            Map<String, Object> cd = apDict(c, (PRef) cid);
            Object fd = dget(cd, "FontDescriptor");
            if (!(fd instanceof PRef)) throw fail();
            Map<String, Object> fdd = apDict(c, (PRef) fd);
            Object ff = dget(fdd, "FontFile2");
            if (!(ff instanceof PRef)) throw fail();
            refs.add((PRef) t0);
            refs.add((PRef) cid);
            refs.add((PRef) fd);
            refs.add((PRef) ff);
            refs.add((PRef) tu);
        }
        Set<Integer> seen = new HashSet<>();
        int[] ids = new int[refs.size()];
        for (int i = 0; i < refs.size(); i++) {
            PRef r = refs.get(i);
            if (r.gen != 0 || !c.isNew.contains(r.num) || seen.contains(r.num)) throw fail();
            seen.add(r.num);
            ids[i] = r.num;
        }
        return ids;
    }

    private static boolean isSpaceByte(int x) {
        return x == 9 || x == 10 || x == 11 || x == 12 || x == 13 || x == 32;
    }

    /** Object num equals, structurally, the parsed writer body. */
    static void sameObject(Classifier c, int num, byte[] body) {
        int s = 0;
        int e = body.length;
        while (s < e && isSpaceByte(body[s] & 0xff)) s++;
        while (e > s && isSpaceByte(body[e - 1] & 0xff)) e--;
        byte[] pre = PdfObjects.latin1(num + " 0 obj\n");
        byte[] post = PdfObjects.latin1("\nendobj\n");
        byte[] src = new byte[pre.length + (e - s) + post.length];
        System.arraycopy(pre, 0, src, 0, pre.length);
        System.arraycopy(body, s, src, pre.length, e - s);
        System.arraycopy(post, 0, src, pre.length + (e - s), post.length);
        PdfParser p = new PdfParser(src, src.length, 0, c.fin.budget);
        PdfParser.Indirect want = p.indirect(null);
        Object got = c.fin.get(num);
        if (!pdfEqual(got, want.val)) throw fail();
    }

    /** The page's (inherited via /Parent) CropBox, else MediaBox, normalized in h100, into box; returns /Rotate. */
    private static int pageGeometry(Classifier c, int num, double[] box) {
        Object b = inherited(c, num, "CropBox");
        if (b == null) b = inherited(c, num, "MediaBox");
        if (!isArr(b) || arr(b).size() != 4) throw fail();
        double[] f = new double[4];
        for (int i = 0; i < 4; i++) {
            Double v = pdfNumber(arr(b).get(i));
            if (v == null) throw fail();
            f[i] = round100(v);
        }
        box[0] = Math.min(f[0], f[2]);
        box[1] = Math.min(f[1], f[3]);
        box[2] = Math.max(f[0], f[2]);
        box[3] = Math.max(f[1], f[3]);
        int rot = 0;
        Object r = inherited(c, num, "Rotate");
        if (r != null) {
            if (!isInt(r) || (Long) r % 90 != 0) throw fail();
            rot = (int) ((((Long) r % 360) + 360) % 360);
        }
        return rot;
    }

    private static Object inherited(Classifier c, int num, String key) {
        Object cur = new PRef(num, 0);
        for (int i = 0; i < 32; i++) {
            if (!(cur instanceof PRef)) return null;
            Object o = c.fin.get(((PRef) cur).num);
            if (!isDict(o)) throw fail();
            Map<String, Object> d = dict(o);
            if (d.containsKey(key)) return c.fin.resolve(dget(d, key));
            cur = dget(d, "Parent");
        }
        throw fail();
    }

    /** An integer or real number with |v| <= 1e7; null otherwise. */
    private static Double pdfNumber(Object x) {
        double v;
        if (isInt(x)) v = (double) (long) (Long) x;
        else if (x instanceof PReal) v = ((PReal) x).v;
        else return null;
        return !Double.isNaN(v) && Math.abs(v) <= 1e7 ? v : null;
    }
}
